-- Settings use the same owner-scoped Realtime refresh as sessions/providers.
-- Safe on fresh and existing projects that already enabled this table manually.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'app_settings'
  ) then
    alter publication supabase_realtime add table public.app_settings;
  end if;
end $$;
